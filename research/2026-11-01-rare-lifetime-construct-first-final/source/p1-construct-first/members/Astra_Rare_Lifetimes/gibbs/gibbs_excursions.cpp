#include <algorithm>
#include <cstdint>
#include <fstream>
#include <iostream>
#include <random>
#include <string>
#include <vector>
using U = unsigned __int128;
// Every random choice has rational probability. Seeded PRNG is the numerical
// realization; the confidence theorem assumes independent ideal random bits.
struct SmallProb { U num,den; };
int width(U a){int n=0;while(a){a>>=1;n++;}return n;}
bool coin(SmallProb p,std::mt19937_64 &rng){
 if(p.num==0)return false;if(p.num>=p.den)return true;
 if(p.den<=U(UINT64_MAX)) {
  std::uniform_int_distribution<uint64_t> d(0,uint64_t(p.den)-1);
  return U(d(rng))<p.num;
 }
 int bits=width(p.den-1);U mask=(U(1)<<bits)-1,z;
 do{z=((U(rng())<<64)|U(rng()))&mask;}while(z>=p.den);
 return z<p.num;
}
int main(int argc,char **argv){
 if(argc!=2)return 2;std::ifstream in(argv[1]);
 int n;uint64_t trials,seed,D,masklo,maskhi,patlo,pathi;
 in>>n>>trials>>seed>>D>>masklo>>maskhi>>patlo>>pathi;
 if(!in||n<2||n>120||D==0)return 3;
 U mask=(U(maskhi)<<64)|masklo,pattern=(U(pathi)<<64)|patlo;
 std::vector<uint64_t>a(n),b(n-1),alpha(n-1);
 for(auto &v:a)in>>v;for(auto &v:b)in>>v;for(auto &v:alpha)in>>v;
 // Exact conditional initial states are generated by Python's Fraction DP
 // and integer rejection sampler. Their generation and bytes are charged.
 std::vector<U> init(trials);
 for(auto &x:init){uint64_t lo,hi;in>>lo>>hi;x=(U(hi)<<64)|lo;
  if((x&mask)!=pattern)return 6;}
 if(!in)return 4;
 std::vector<std::vector<SmallProb>> hb(n,std::vector<SmallProb>(4));
 for(int i=0;i<n;i++)for(int c=0;c<4;c++){
  U num=a[i],den=D;
  if(i>0&&(c&1)){num*=b[i-1];den*=D;}
  if(i+1<n&&(c&2)){num*=b[i];den*=D;}
  hb[i][c]={num,num+den};
 }
 std::vector<std::vector<SmallProb>> cyc(n-1,std::vector<SmallProb>(16));
 for(int i=0;i<n-1;i++)for(int c=0;c<16;c++){
  bool l=c&1,x=c&2,y=c&4,r=c&8;U num=1,den=1;
  auto mul=[&](uint64_t v){num*=v;den*=D;};
  if(x)mul(a[i]);if(y)mul(a[i+1]);
  if(i>0&&l&&x)mul(b[i-1]);if(x&&y)mul(b[i]);
  if(i+2<n&&y&&r)mul(b[i+1]);
  cyc[i][c]={U(alpha[i])*den,U(2)*D*num};
  if(cyc[i][c].num>cyc[i][c].den)return 5;
 }
 std::mt19937_64 rng(seed);
 auto bit=[](U x,int i){return int((x>>i)&1);};
 auto move=[&](U x,int k){
  if(k<n){int c=(k>0?bit(x,k-1):0)+2*(k+1<n?bit(x,k+1):0);
   bool v=coin(hb[k][c],rng);U m=U(1)<<k;return (x&~m)|(U(v)<<k);}
  int i=k-n;int old=bit(x,i)+2*bit(x,i+1);
  static const int fwd[4]={1,3,2,0},rev[4]={3,0,2,1};
  if(old==2)return x;
  int c=(i>0?bit(x,i-1):0)+2*bit(x,i)+4*bit(x,i+1)+8*(i+2<n?bit(x,i+2):0);
  if(!coin(cyc[i][c],rng))return x;
  int next=(i&1)?rev[old]:fwd[old];U m=(U(1)<<i)|(U(1)<<(i+1));
  return (x&~m)|(U(next&1)<<i)|(U((next>>1)&1)<<(i+1));
 };
 std::vector<int> relevant,cum;int rtotal=0;
 for(int k=0;k<2*n-1;k++){
  U support=k<n?(U(1)<<k):((U(1)<<(k-n))|(U(1)<<(k-n+1)));
  if(support&mask){rtotal+=(k<n?40:80);relevant.push_back(k);cum.push_back(rtotal);}
 }
 int total=40*n+80*(n-1);
 std::uniform_int_distribution<int> initial(0,rtotal-1),event(0,total);
 uint64_t success=0,exits=0,events=0,max_events=0,conditional_bits=0;
 for(uint64_t z=0;z<trials;z++){
  U x=init[z];
  for(int i=0;i<n;i++)if(!((mask>>i)&1))conditional_bits++;
  int ix=std::upper_bound(cum.begin(),cum.end(),initial(rng))-cum.begin();
  x=move(x,relevant[ix]);if((x&mask)==pattern)continue;
  exits++;uint64_t count=0;
  while(true){
   count++;int k=event(rng);
   if(k==total){success++;break;}
   int m=k<40*n?k/40:n+(k-40*n)/80;
   x=move(x,m);if((x&mask)==pattern)break;
  }
  events+=count;max_events=std::max(max_events,count);
 }
 std::cout<<"{\"trials\":"<<trials<<",\"successes\":"<<success
  <<",\"initial_exits\":"<<exits<<",\"events\":"<<events
  <<",\"initial_boundary_proposals\":"<<trials
  <<",\"total_proposal_calls\":"<<events+trials
  <<",\"max_events_one_trial\":"<<max_events
  <<",\"conditional_free_bit_draws\":"<<conditional_bits
  <<",\"relevant_weight\":"<<rtotal<<",\"total_weight\":"<<total
  <<",\"killing_weight\":1,\"rate_denominator\":40}\n";
}
