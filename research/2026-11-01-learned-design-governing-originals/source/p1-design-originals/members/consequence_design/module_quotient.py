class PreparedEnergySource:
    """A synthetic implementation of the charged experimental interface.

    Source evaluation uses dense quadratic matrices only inside this class.
    The arbitrary context nuisance is generated by a deterministic 64-bit hash;
    it is not a structural promise given to the learner. Actual noise samples,
    including every averaging repetition, are generated and counted.
    """
    def __init__(self, k, theta, amplitude, sigma, seed):
        self.k, self.n = int(k), 2*int(k)
        self.sigma = float(sigma)
        self._amplitude = float(amplitude)
        self._theta = np.asarray(theta, dtype=float).copy()
        self._b = self._theta[:k].copy()
        self._U, self._V, self._W = [np.zeros((k, k)) for _ in range(3)]
        at = k
        for a in range(k):
            for b in range(a+1, k):
                self._U[a, b], self._V[a, b], self._W[a, b] = self._theta[at:at+3]
                at += 3
        self.rng = np.random.default_rng(seed)
        self.energy_samples = self.prepared_configurations = self.control_bit_changes = 0
        self.max_absolute_report = 0.
        self._last = None

    def costs(self):
        return {"energy_samples": self.energy_samples,
                "prepared_configurations": self.prepared_configurations,
                "control_bit_changes": self.control_bit_changes}

    def _nuisance(self, counts):
        z = np.full(len(counts), np.uint64(0x517CC1B727220A95), dtype=np.uint64)
        with np.errstate(over="ignore"):
            for a in range(self.k):
                z ^= counts[:, a].astype(np.uint64)+np.uint64(0x9E3779B97F4A7C15)
                z = (z^(z >> np.uint64(30)))*np.uint64(0xBF58476D1CE4E5B9)
                z = (z^(z >> np.uint64(27)))*np.uint64(0x94D049BB133111EB)
                z ^= z >> np.uint64(31)
        return self._amplitude*(z.astype(np.float64)/float(2**64)-.5)

    def _mean(self, x, nuisance=True):
        modules = x.reshape(len(x), self.k, 2).astype(float)
        q = (modules[:, :, 0]-modules[:, :, 1])/math.sqrt(2)
        s = (modules[:, :, 0]+modules[:, :, 1])/math.sqrt(2)
        value = (q@self._b + np.einsum("bi,ij,bj->b", q, self._U, q, optimize=True)
                 + np.einsum("bi,ij,bj->b", q, self._V, s, optimize=True)
                 + np.einsum("bi,ij,bj->b", s, self._W, q, optimize=True))
        if nuisance:
            counts = ((modules.sum(axis=2)+2)/2).astype(np.uint64)
            value += self._nuisance(counts)
        return value

    def measure_many(self, configurations, repetitions=1):
        x = np.asarray(configurations, dtype=np.int8)
        if x.ndim == 1:
            x = x[None, :]
        if x.shape[1] != self.n or np.any(np.abs(x) != 1):
            raise ValueError("Only prepared binary configurations are allowed")
        repetitions = int(repetitions)
        if repetitions < 1:
            raise ValueError("At least one source observation is required")
        self.control_bit_changes += (self.n if self._last is None else
                                     int(np.count_nonzero(x[0] != self._last)))
        self.control_bit_changes += int(np.count_nonzero(x[1:] != x[:-1]))
        self._last = x[-1].copy()
        self.prepared_configurations += len(x)
        self.energy_samples += len(x)*repetitions
        result = np.empty(len(x))
        for start in range(0, len(x), 1024):
            part = x[start:start+1024]
            # Generate all physical-shot errors; no aggregate-binomial shortcut.
            noise = self.rng.normal(0., self.sigma, (len(part), repetitions)).mean(axis=1)
            result[start:start+len(part)] = self._mean(part)+noise
        self.max_absolute_report = max(self.max_absolute_report, float(np.max(np.abs(result))))
        return result


def project_forest(theta, k):
    """Actual exact Euclidean grouped-forest projection (float comparisons)."""
    pairs = [(a, b) for a in range(k) for b in range(a+1, k)]
    edge_values = np.asarray(theta[k:]).reshape(-1, 3)
    weight = np.sum(edge_values**2, axis=1)
    order = np.argsort(-weight, kind="stable")
    parent = np.arange(k)

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = int(parent[a])
        return a

    result = np.zeros_like(theta)
    result[:k] = theta[:k]
    selected = []
    for e in order:
        a, b = pairs[e]
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra
            result[k+3*e:k+3*e+3] = edge_values[e]
            selected.append(int(e))
            if len(selected) == k-1:
                break
    return result, selected


def acquire_module_forest(source, k, rows, iterations, seed, repetitions=1,
                          step=1., refit=True):
    """Learning uses no true coefficients, graph, nuisance values or optimizer."""
    rng = np.random.default_rng(seed)
    configurations, random_cost = module_orbit_pairs(rng, rows, 2*k)
    features = module_features(configurations)
    design = (features[0::2]-features[1::2])/math.sqrt(2)
    del features
    before = source.costs()
    observed = source.measure_many(configurations, repetitions)
    response = (observed[0::2]-observed[1::2])/math.sqrt(2)
    after = source.costs()
    D = design.shape[1]
    theta = np.zeros(D)
    records = []
    start = time.perf_counter()
    last_support = None
    stable_support_steps = 0
    for t in range(iterations):
        residual = response-design@theta
        proposal = theta+step*(design.T@residual)/rows
        next_theta, selected = project_forest(proposal, k)
        change = float(np.linalg.norm(next_theta-theta))
        theta = next_theta
        support = tuple(sorted(selected))
        stable_support_steps = stable_support_steps+1 if support == last_support else 0
        last_support = support
        if t % 10 == 0 or t == iterations-1:
            records.append({"iteration": t+1,
                            "paired_training_RMS": float(np.linalg.norm(response-design@theta)/math.sqrt(rows)),
                            "coefficient_change": change,
                            "forest_edges": len(selected)})
        if not np.all(np.isfinite(theta)) or np.linalg.norm(theta) > 1.e10:
            raise RuntimeError("This proposed IHT run diverged; more data or another proposal is needed")
        if change < 1.e-10 and stable_support_steps >= 5:
            break
    refit_record = None
    if refit:
        support_indices = list(range(k))
        for e in selected:
            support_indices.extend(range(k+3*e, k+3*e+3))
        support_indices = np.array(sorted(support_indices), dtype=int)
        old_rms = float(np.linalg.norm(response-design@theta)/math.sqrt(rows))
        fitted, _, rank, singular = np.linalg.lstsq(design[:, support_indices], response, rcond=None)
        theta = np.zeros(D)
        theta[support_indices] = fitted
        refit_record = {"support_dimension": len(support_indices), "actual_matrix_rank": int(rank),
                        "before_RMS": old_rms,
                        "after_RMS": float(np.linalg.norm(response-design@theta)/math.sqrt(rows)),
                        "smallest_support_singular_value": float(singular[-1]/math.sqrt(rows))}
    candidate = ModuleForestModel(k, theta)
    elapsed = time.perf_counter()-start
    return candidate, {
        "method": "paired_orbit_contrasts_then_grouped_forest_model_IHT",
        "modules": k, "physical_sites": 2*k, "noninvariant_feature_dimension": D,
        "experimental_pair_rows": rows, "source_repetitions_per_reading": repetitions,
        "distinct_training_resource_contexts": len({row.tobytes() for row in
            ((configurations[0::2].reshape(rows, k, 2).sum(axis=2)+2)//2)}),
        "iterations_executed": t+1, "step": step,
        "refit": refit_record, "iteration_record": records,
        "training_wall_seconds": elapsed,
        "dense_design_entries_used_in_training": int(rows*D),
        "retained_unary_coefficients": k,
        "retained_edge_groups": len(candidate.edge_groups()),
        "retained_noninvariant_coefficients": k+3*len(candidate.edge_groups()),
        "source_cost": {name: after[name]-before[name] for name in after},
        **random_cost,
        "sufficient_theorem_constants_executed": False,
        "soundness_basis": "fresh independent accepted operation-quotient certificate"
    }


def _dense_coefficients(candidate):
    if hasattr(candidate, "coefficient_vector"):
        return candidate.coefficient_vector()
    return candidate.theta


def query_checks(candidate, true_theta, certificate, queries, seed, enumerate_limit=16):
    """Independent checker; never called by acquisition or the service."""
    rng = np.random.default_rng(seed)
    k = candidate.k
    records = []
    previous = np.ones(2*k, dtype=np.int8)
    max_gap = max_regret = 0.
    for t in range(queries):
        occupancy = rng.integers(0, 3, k)
        if t == 0:
            occupancy[:] = 1
        elif t == 1:
            occupancy[:] = 0
        elif t % 3 == 0:
            occupancy = ((previous.reshape(k, 2)[:, 0] > 0).astype(int)+t) % 3
        if k > enumerate_limit and t in (2, 6, 10, 14):
            # Several later requests deliberately leave a small but nontrivial
            # active set so an independent full scorer can check the service.
            occupancy = 2*rng.integers(0, 2, k)
            occupancy[rng.choice(k, min(12, k), replace=False)] = 1
        fields = rng.uniform(-.6, .6, 2*k)+.1*previous
        # A query near a local placement decision boundary is selected using
        # only the acquired forest, so small residual effects are observable.
        if t % 4 == 2 and np.any(occupancy == 1):
            selected = int(np.flatnonzero(occupancy == 1)[0])
            active = np.flatnonzero(occupancy == 1)
            if len(active) <= enumerate_limit:
                possible = feasible_orientations(occupancy)
                base_fields = fields.copy()
                base_fields[2*selected] = base_fields[2*selected+1] = 0.
                values = candidate.evaluate(possible)+possible@base_fields
                plus = float(np.min(values[possible[:, 2*selected] == 1]))
                minus = float(np.min(values[possible[:, 2*selected] == -1]))
                fields = base_fields
                fields[2*selected] = (minus-plus)/4
                fields[2*selected+1] = -(minus-plus)/4
        start = time.perf_counter()
        answer, operations = candidate.solve_context(occupancy, fields)
        elapsed = time.perf_counter()-start
        active_count = int(np.sum(occupancy == 1))
        bound = (2*math.sqrt(2*active_count*(2*k-active_count))
                 *certificate["quotient_residual_norm_upper"])
        record = {"query": t, "active_modules": active_count,
                  "context": occupancy.tolist(), "context_regret_upper": bound,
                  "execution_wall_seconds": elapsed, **operations,
                  "physical_source_calls_for_execution": 0}
        if active_count <= enumerate_limit:
            feasible = feasible_orientations(occupancy)
            fitted = candidate.evaluate(feasible)+feasible@fields
            actual = module_features(feasible)@true_theta+feasible@fields
            gap = float(candidate.evaluate(answer)+answer@fields-np.min(fitted))
            regret = float((module_features(answer)@true_theta)[0]+answer@fields-np.min(actual))
            assert abs(gap) < 1.e-8
            assert -1.e-8 <= regret <= bound+1.e-8
            record.update({"checked_by_orientation_enumeration": True,
                           "enumerated_feasible_configurations": len(feasible),
                           "surrogate_gap": gap, "true_regret": regret})
            max_gap, max_regret = max(max_gap, gap), max(max_regret, regret)
        else:
            record["checked_by_orientation_enumeration"] = False
        previous = answer
        records.append(record)
    return {"queries": records, "max_checked_surrogate_gap": max_gap,
            "max_checked_true_regret": max_regret}


def run_fixture(k, rows, iterations, seed, validate=True):
    theta, true_tree = make_module_fixture(k, seed, dense_tail=.002)
    source = PreparedEnergySource(k, theta, amplitude=1.e4, sigma=.002, seed=seed+1)
    t0 = time.perf_counter()
    candidate, training = acquire_module_forest(source, k, rows, iterations, seed+2)
    if not validate:
        error = float(np.linalg.norm(theta-_dense_coefficients(candidate)))
        return {"training": training, "fixture_only_quotient_error": error,
                "true_tree_recovered": {(a, b) for a, b, _ in candidate.edge_groups()} == true_tree}
    certificate = statistical_validate_group_action(
        source, candidate, .02, module_orbit_pairs, math.sqrt(2)*k,
        global_failure=.05, candidate_number=1, seed=seed+3)
    if not certificate["accepted"]:
        raise RuntimeError("Candidate failed its independent operational certificate")
    error = float(np.linalg.norm(theta-_dense_coefficients(candidate)))
    assert error <= certificate["quotient_residual_norm_upper"]+1.e-9
    checks = query_checks(candidate, theta, certificate, 16, seed+4)
    # Full-model regression is algebraically underdetermined with these same
    # paired observations when rows<D. This is not a claim that another
    # structural learner using the same data cannot match the construction.
    result = {"modules": k, "physical_sites": 2*k,
              "resource_contexts": str(3**k), "full_configurations": str(4**k),
              "arbitrary_context_nuisance_amplitude": 1.e4,
              "absolute_noise_sigma": source.sigma,
              "largest_absolute_report": source.max_absolute_report,
              "training": training, "certificate": certificate,
              "fixture_only_quotient_residual_norm": error,
              "fixture_only_true_nonzero_module_edges": k*(k-1)//2,
              "fixture_only_planted_tree_recovered": {(a,b) for a,b,_ in candidate.edge_groups()} == true_tree,
              "full_unstructured_linear_reconstruction_underdetermined": rows < len(theta),
              "adaptive_service_checks": checks,
              "total_source_cost": source.costs(),
              "wall_seconds": time.perf_counter()-t0,
              "limitations": ["Synthetic prepared-energy source, not physical deployment",
                              "Floating arithmetic, not interval-verified numeric certification",
                              "No claim of novelty for IHT, Kruskal or tree DP",
                              "No speedup claim over task-aware sparse recovery using the same quotient contrasts",
                              "Only small feasible orientation sets independently enumerated"]}
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--modules", type=int, default=32)
    parser.add_argument("--rows", type=int, default=768)
    parser.add_argument("--iterations", type=int, default=100)
    parser.add_argument("--seed", type=int, default=7143)
    parser.add_argument("--training-only", action="store_true")
    parser.add_argument("--output", default="module_quotient_results.json")
    args = parser.parse_args()
    result = run_fixture(args.modules, args.rows, args.iterations, args.seed,
                         validate=not args.training_only)
    destination = HERE/args.output
    destination.write_text(json.dumps(result, indent=2)+"\n")
    print(json.dumps({"output": str(destination),
                      "modules": args.modules,
                      "training_source_calls": result["training"]["source_cost"]["energy_samples"],
                      "training_error": result.get("fixture_only_quotient_error",
                                                   result.get("fixture_only_quotient_residual_norm")),
                      "accepted": result.get("certificate", {}).get("accepted"),
                      "wall_seconds": result.get("wall_seconds")}, indent=2))


if __name__ == "__main__":
    main()
