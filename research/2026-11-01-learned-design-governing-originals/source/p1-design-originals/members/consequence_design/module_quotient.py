"""Acquire and execute a resource-quotient design service.

Only the fixture source and independent scorer see true coefficients. The
learner gets chosen-configuration readings; it constructs its own module forest.
The validation code uses fresh within-resource contrasts. Numerical code uses
float64 and PRNGs; it is not an interval-verified hardware implementation.
"""
