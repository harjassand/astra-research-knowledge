"""Finite checks of the fixed-source masking construction.

The spherical-cap and adaptive coupling proof supplies the lower bound. These
checks verify oracle admissibility, identical finite transcripts, a revealing
demand, and finite-sample spherical caps. They are not proof by experiment.
"""
from fractions import Fraction as F
from pathlib import Path
import json
import math
import numpy as np


def run():
    # An exact coordinate-query fixture: N=65, hidden u=(0,1/8,...,1/8).
    n=65
    beta=F(1)
    eta=F(1,4)
    u=[F(0)]+[F(1,8)]*64
    assert sum(x*x for x in u)==1
    assert all(beta*beta*x*x<=eta*eta for x in u)
    coordinate_errors=[beta*abs(x) for x in u]
    assert max(coordinate_errors)==F(1,8)
    # Every coordinate returns exactly A0 e_i under the same fixed oracle.
    exact={
        'ambient_dimension':n,
        'coordinate_queries':n,
        'all_coordinate_queries_masked':True,
        'maximum_exact_error_norm':str(max(coordinate_errors)),
        'allowed_error_norm':str(eta),
        'source_algebra_dimensions':[2,2],
        'source_condition_numbers':[2,2],
        'positive_polynomial_trace_baseline':1,
        'positive_polynomial_trace_spike':2,
        'hidden_direction_inverse_difference':str(F(1,2)),
        'one_demand_query_signal':str(beta-eta),
        'baseline_maximum_demand_error':str(eta),
    }
    assert beta-eta>eta

    # A fixed high-dimensional source and soft-threshold oracle. The source
    # direction is selected before the query seed. Queries also include repeats
    # and nonlinear functions of previous returned vectors.
    rng_source=np.random.default_rng(3701)
    n=513
    u=rng_source.normal(size=n)
    u[0]=0
    u/=np.linalg.norm(u)
    eta=0.22
    beta=lam=1.0
    def base(v):
        ans=lam*v.copy()
        ans[0]+=beta*v[0]
        return ans
    def true(v):return base(v)+beta*u*np.dot(u,v)
    def oracle(v):
        t=np.dot(u,v)
        return base(v)+u*np.sign(t)*max(beta*abs(t)-eta*np.linalg.norm(v),0.0)
    rng_query=np.random.default_rng(4419)
    max_ratio=0.0
    masked=0
    outputs=[]
    q=256
    for i in range(q):
        v=rng_query.normal(size=n)
        if i and i%4==0:v+=0.3*np.tanh(outputs[-1])
        y=oracle(v)
        err=np.linalg.norm(y-true(v))
        ratio=err/np.linalg.norm(v)
        assert ratio<=eta*(1+1e-12)
        max_ratio=max(max_ratio,ratio)
        masked+=int(np.array_equal(y,base(v)))
        outputs.append(y)
    assert masked==q
    reveal=np.linalg.norm(oracle(u)-base(u))
    assert abs(reveal-(beta-eta))<1e-12
    coupled={
        'ambient_dimension':n,
        'adaptive_queries':q,
        'masked_queries':masked,
        'maximum_action_error_ratio':max_ratio,
        'allowed_error_ratio':eta,
        'demand_direction_signal':reveal,
        'union_bound_on_any_unmasking':min(1,2*q*math.exp(-(n-1)*eta**2/(2*beta**2))),
    }

    # Sphere-coordinate probabilities versus the elementary moment bound.
    rng=np.random.default_rng(85011)
    trials=20000
    dimension=128
    # The first coordinate can be generated by one normal and a chi-square sum.
    first=rng.normal(size=trials)
    remainder=rng.chisquare(dimension-1,size=trials)
    coordinates=first/np.sqrt(first*first+remainder)
    caps=[]
    for threshold in (0.1,0.2,0.3):
        caps.append({'sphere_dimension':dimension,'threshold':threshold,
                     'observed_frequency':float(np.mean(np.abs(coordinates)>threshold)),
                     'proved_upper_bound':min(1,2*math.exp(-dimension*threshold**2/2))})

    # Paid precision removes the hiding scale for the detection task. Scalar
    # sphere coordinates suffice to simulate the worst soft-threshold response.
    # The guarantee holds for all allowed error directions, by the proof.
    calibrated=[]
    delta=0.05
    probe_count=math.ceil(12*math.log(1/delta))
    for m in (64,512,4096):
        eta_cal=1/(4*math.sqrt(m))
        first=rng.normal(size=trials)
        remainder=rng.chisquare(m-1,size=trials)
        coord=first/np.sqrt(first*first+remainder)
        signal=np.abs(coord)
        observed_response_norm=np.maximum(signal-eta_cal,0)
        detection=observed_response_norm>eta_cal
        assert np.all(detection[signal>2*eta_cal])
        calibrated.append({'sphere_dimension':m,'requested_eta':eta_cal,
                           'empirical_one_query_detection':float(np.mean(detection)),
                           'proved_one_query_detection_lower_bound':1/12,
                           'queries_for_delta_0_05':probe_count,
                           'proved_miss_upper_bound':math.exp(-probe_count/12),
                           'precision_work_p2':probe_count*eta_cal**(-2),
                           'p2_work_divided_by_m':probe_count*eta_cal**(-2)/m})
    return {'status':'masking_and_demand_checks_passed','exact_coordinate_fixture':exact,
            'fixed_source_adaptive_fixture':coupled,'sphere_cap_checks':caps,
            'calibrated_detection_checks':calibrated,
            'qualification':'Finite examples; the ordinary proof, not Monte Carlo, establishes the lower bound.'}


if __name__=='__main__':
    result=run()
    Path(__file__).with_name('masking_obstruction_results.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2))
