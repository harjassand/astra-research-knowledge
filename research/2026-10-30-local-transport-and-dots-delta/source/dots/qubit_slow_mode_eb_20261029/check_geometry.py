import numpy as np, scipy.linalg as la, json, math
from pathlib import Path
rng=np.random.default_rng(20261029)
P=[np.eye(2),np.array([[0,1],[1,0]],complex),np.array([[0,-1j],[1j,0]],complex),np.diag([1,-1])]
S=np.array([[1,0,0],[0,1/np.sqrt(2),0],[0,1/np.sqrt(2),0],[0,0,1]],complex)
def affine(K):
 def ch(A): return sum(k@A@k.conj().T for k in K)
 t=np.array([np.trace(p@ch(P[0])/2).real for p in P[1:]])
 T=np.array([[np.trace(p@ch(q)/2).real for q in P[1:]] for p in P[1:]])
 return T,t
def rot():
 Q,_=np.linalg.qr(rng.normal(size=(3,3)))
 if np.linalg.det(Q)<0: Q[:,0]*=-1
 return Q
def near_clone(eps):
 H=rng.normal(size=(3,3))+1j*rng.normal(size=(3,3)); H=(H+H.conj().T)/2
 V=S@la.expm(1j*eps*H)[:,[0,2]]
 K=[V.reshape(2,2,2)[:,j,:] for j in range(2)]
 T,t=affine(K)
 # small relative output unitary rotation followed by common input/output gauge
 a=rng.normal(size=3); a*=eps/(np.linalg.norm(a)+1e-30)
 A=np.array([[0,-a[2],a[1]],[a[2],0,-a[0]],[-a[1],a[0],0]])
 Q=la.expm(A); T=Q@T; t=Q@t
 # output amplitude damping (postprocessing preserves compatibility)
 if rng.random()<.8:
  gamma=min(.3,eps**2*10**rng.uniform(-1,1))
  R=rot(); D=R@np.diag([np.sqrt(1-gamma),np.sqrt(1-gamma),1-gamma])@R.T
  T=D@T; t=D@t+gamma*R[:,2]
 Q=rot(); return Q@T@Q.T,Q@t

def tnorm(A): return np.linalg.svd(A,compute_uv=False).sum().real

def map_affine(T,t,A):
 tr=np.trace(A); c=np.array([np.trace(p@A) for p in P[1:]])
 z=T@c+tr*t
 return (tr*P[0]+sum(z[j]*P[j+1] for j in range(3)))/2

def choi(T,t):
 J=np.zeros((4,4),complex)
 for i in range(2):
  for j in range(2):
   A=np.zeros((2,2));A[i,j]=1
   J[2*i:2*i+2,2*j:2*j+2]=map_affine(T,t,A)/2
 return J

results=[]; maxima=dict(singular_sum=0., endpoint_excess=-1.,identity_error=0.,fixed_error=0.,quotient_norm=0.,ratio=0.)
mins=dict(choi=1.,ppt=1.)
near_count=far_count=0
for idx in range(2400):
 eps=10**rng.uniform(-4.7,-.3)
 T,t=near_clone(eps)
 s=np.linalg.solve(np.eye(3)-T,t)
 if np.linalg.norm(s)>1+1e-5: raise AssertionError(('fixed outside',idx,s))
 sv=np.linalg.svd(T,compute_uv=False); maxima['singular_sum']=max(maxima['singular_sum'],sv[0]**2+sv[1]**2)
 ev,V=np.linalg.eig(T.T); inds=[j for j,l in enumerate(ev) if abs(l.imag)<1e-8 and l.real>=.99]
 if inds:
  near_count+=1; j=inds[0]; lam=ev[j].real; g=1-lam
  if g<0 and g>-1e-12:g=0
  w=V[:,j].real; w/=np.linalg.norm(w)
  W=la.null_space(w.reshape(1,3)); Q=np.column_stack([w,W]); Tb=Q.T@T@Q; sb=Q.T@s
  u=sb[0];v=sb[1:];a=Tb[1:,0];B=Tb[1:,1:]
  h=np.linalg.solve(lam*np.eye(2)-B,a); n=np.r_[1.,h]; k=1-16*g
  rp=sb+k*(1-u)*n;rm=sb+k*(-1-u)*n
  TFb=k*np.outer(n,[1,0,0]);TF=Q@TFb@Q.T;tf=s-TF@s
  D=np.linalg.inv(np.eye(2)-B)
  Lb=np.zeros((3,3)); Lb[0,0]=16; Lb[1:,0]=(16*np.eye(2)-D)@h; Lb[1:,1:]=D
  L=Q@Lb@Q.T
  maxima['endpoint_excess']=max(maxima['endpoint_excess'],np.linalg.norm(rp)-1,np.linalg.norm(rm)-1)
  # Per-sign exact analytical inequalities tested, not inferred.
  for sign,q in [(1,1-u),(-1,1+u)]:
   xx=(np.eye(2)-B)@v+a*(sign-u)
   yy=v+(sign-u)*h
   assert np.linalg.norm(xx)**2<=2*g*q+2e-10
   assert np.linalg.norm(v)<=5*np.sqrt(max(0,g*q))+2e-7
   assert np.linalg.norm(yy)<=4*np.sqrt(max(0,g*q))+2e-7
 else:
  far_count+=1; TF=np.zeros((3,3));tf=s;L=np.linalg.inv(np.eye(3)-T)
 maxima['quotient_norm']=max(maxima['quotient_norm'],np.linalg.norm(L,2))
 maxima['identity_error']=max(maxima['identity_error'],np.linalg.norm(np.eye(3)-TF-L@(np.eye(3)-T)))
 maxima['fixed_error']=max(maxima['fixed_error'],np.linalg.norm(TF@s+tf-s))
 J=choi(TF,tf); pt=J.reshape(2,2,2,2).transpose(0,3,2,1).reshape(4,4)
 mins['choi']=min(mins['choi'],np.linalg.eigvalsh(J).min())
 mins['ppt']=min(mins['ppt'],np.linalg.eigvalsh(pt).min())
 if idx<120:
  # Arbitrary reference dimension three, arbitrary correlated states.
  d=3;X=rng.normal(size=(2*d,2*d))+1j*rng.normal(size=(2*d,2*d));rho=X@X.conj().T;rho/=np.trace(rho)
  def stab(T,t):
   out=np.zeros_like(rho)
   for a0 in range(d):
    for b0 in range(d):
     A=rho.reshape(2,d,2,d)[:,a0,:,b0]
     out.reshape(2,d,2,d)[:,a0,:,b0]=map_affine(T,t,A)
   return out
  residual=tnorm(rho-stab(T,t));err=tnorm(rho-stab(TF,tf));ratio=err/residual if residual>1e-14 else 0
  maxima['ratio']=max(maxima['ratio'],ratio)
  assert err<=3*np.linalg.norm(L,2)*residual+1e-9
 assert maxima['identity_error']<1e-7
 assert mins['choi']>-1e-7 and mins['ppt']>-1e-7
out=dict(samples=2400,near=near_count,far=far_count,maxima=maxima,minima=mins,note='Floating diagnostic only. Channels generated by actual symmetric isometries followed by CPTP postprocessings; proof is analytic.')
Path(__file__).with_name('GEOMETRY_CHECKS.json').write_text(json.dumps(out,indent=2))
