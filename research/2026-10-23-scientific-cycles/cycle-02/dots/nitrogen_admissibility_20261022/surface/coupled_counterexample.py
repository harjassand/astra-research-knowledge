"""Thermodynamic non-identifiability counterexample; NOT a zirconia rate estimate.
A small isolated gas/finite-solid cell uses one source snapshot's gas inventory,
geometry, solid heat capacity and exact formation-energy thermochemistry. A
transparent LTE common-temperature contact idealization, not the original bed,
is used. Existing homogeneous chemistry is retained. Added surface chemistry is
reversible, collision-bounded, site-conserving and entropy-producing. Only its
common kinetic factor differs between completions; no factor is material-qualified.
"""
from pathlib import Path
import sys, json, hashlib, time, resource
import numpy as np
from scipy.integrate import solve_ivp, trapezoid
from scipy.optimize import brentq
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'nitrogen_finite_cycle_20261021'
sys.path.insert(0,str(SOURCE)); import reacting_heater_signed as m
OUT=Path(__file__).resolve().parent
R=m.K.R/1000.; W=m.K.W/1000.; NU=np.array([1.,1.,0.,0.,-2.,0.])
source=SOURCE/'heater_H4_signed_T11_blow_10.npz'
z=np.load(source); snap=z['state'][:,-1]; q,rho,U,p=m.props(snap); i=m.M-1
V=float(m.vol[i]); Csolid=m.CS*m.dx; Ageom=6*(1-m.por)/m.dp*m.dx
n0=q[:,i]*V/W
Tg0=float(p['T'][i]); Ts0=float(snap[m.ngas+m.nsolid-1]*1000.)
# Finite, explicitly hypothetical catalyst amount. It is identical and remains
# unchanged in every completion. This value is NOT a measured zirconia site count.
Nsite=1e-5*Ageom

def therm(T):
 cp,h,s=m.K.thermochemistry(np.array([float(T)]))
 return cp[:,0]*R, h[:,0]*R*T, s[:,0]*R

def energy(n,T):
 cp,h,s=therm(T); return float(n@(h-R*T)+Csolid*T)

def entropy(n,T):
 cp,h,s=therm(T); a=n*R*T/(V*m.P0)
 return float(np.sum(n*(s-R*np.log(np.maximum(a,1e-300))))+Csolid*np.log(T))

cp,h,s=therm(Tg0)
Ustart=float(n0@(h-R*Tg0)+Csolid*Ts0)
Tstart=brentq(lambda T:energy(n0,T)-Ustart, min(Tg0,Ts0),max(Tg0,Ts0),xtol=1e-10)

def surface(n,T,lam):
 # 2 NO + C <=> N2 + O2 + C. The two stable surface states are identical.
 # A finite active center C is regenerated by EACH event, so its exact state and
 # finite inventory reset at every time. No atom is removed into the solid.
 cp,h,s=therm(T); gRT=(h-T*s)/(R*T)
 logKd=float(-NU@gRT)
 a=n*R*T/(V*m.P0)
 F=a[4]**2; B=a[0]*a[1]*np.exp(-logKd)
 # Common blocking factor preserves f/b=Kd*a_NO^2/(a_N2*a_O2).
 # vstar <= each reactant's one-sided thermal velocity. The denominator makes
 # 2f <= lam*J_NO, b <= (lam/2)*J_N2, b <= (lam/2)*J_O2 for a_i >= 0.
 D=1+a[4]+(a[0]+a[1])*np.exp(-logKd)
 vstar=np.sqrt(R*T/(2*np.pi*max(W)))
 Jstar=m.P0/(R*T)*vstar
 pref=Ageom*lam*Jstar/(2*D)
 f=pref*F; b=pref*B; net=f-b
 affinity=R*T*np.log(F/B) if F>0 and B>0 else 0.
 J=n/V*np.sqrt(R*T/(2*np.pi*W))*Ageom
 return net,f,b,affinity,logKd,J

def rhs(t,y,lam):
 n=y[:6];T=y[6]
 rates=m.K.signed_rates(np.array([T]),(n/(1000*V))[:,None])[0][:,0]
 hom=(m.K.nu@rates)*(1000*V)
 surf=surface(n,T,lam)[0]
 dn=hom+NU*surf
 cp,h,s=therm(T); cv=cp-R;u=h-R*T
 dT=-float(u@dn)/(Csolid+float(n@cv))
 return np.r_[dn,dT,surf]

def calculate(lam, method="BDF", rtol=2e-10, max_step=.01):
 y0=np.r_[n0,Tstart,0.]
 sol=solve_ivp(lambda t,y:rhs(t,y,lam),(0.,1.),y0,method=method,rtol=rtol,atol=np.r_[np.full(6,1e-19),1e-9,1e-19],max_step=max_step)
 if not sol.success:raise RuntimeError(sol.message)
 n=sol.y[:6];T=sol.y[6]
 profiles=[surface(nn,float(tt),lam) for nn,tt in zip(n.T,T)]
 en=np.array([energy(nn,float(tt)) for nn,tt in zip(n.T,T)])
 ent=np.array([entropy(nn,float(tt)) for nn,tt in zip(n.T,T)])
 atoms=np.array([[2,0,1,0,1,1],[0,2,0,1,1,2]])
 atomerr=atoms@(n-n0[:,None])
 rf=np.array([v[1] for v in profiles]);rr=np.array([v[2] for v in profiles]);af=np.array([v[3] for v in profiles]);rn=rf-rr
 J=np.stack([v[5] for v in profiles],axis=1)
 denom=np.maximum(J,1e-300)
 nox0=float(n0[4:6].sum());noxfinal=float(n[4:6,-1].sum())
 # An appended catalyst-only sensible reset after disconnecting the parcel has
 # finite positive heat removal. No surface atoms or chemical state require reset.
 # This is a boundary ledger, not a model of valve/cooling/capture hardware.
 reset_heat=Csolid*(float(T[-1])-Tstart)
 return {
  'lambda_dimensionless_hypothetical':lam,'success':sol.success,'steps':len(sol.t)-1,'nfev':sol.nfev,
  'initial_NOx_mol_m2_crosssection':nox0,'final_NOx_mol_m2_crosssection':noxfinal,
  'retained_NOx_fraction':noxfinal/nox0,'NOx_loss_fraction':1-noxfinal/nox0,
  'gas_species_initial_mol_m2':n0.tolist(),'gas_species_final_mol_m2':n[:,-1].tolist(),
  'initial_common_T_K':Tstart,'final_common_T_K':float(T[-1]),'max_T_K':float(max(T)),
  'direct_surface_NO_destroyed_mol_m2':2*float(sol.y[7,-1]),
  'signed_catalytic_turnovers_per_site':float(sol.y[7,-1]/Nsite),
  'site_inventory_mol_m2_crosssection':Nsite,'site_inventory_change_mol_m2':0.,
  'site_chemical_state_reset_exact':True,
  'solid_sensible_reset_heat_to_300K_environment_J_m2':reset_heat,
  'solid_reset_entropy_production_J_m2_K':reset_heat/300-Csolid*np.log(float(T[-1])/Tstart),
  'max_energy_residual_J_m2':float(max(abs(en-en[0]))),
  'max_element_residual_mol_atoms_m2':float(np.max(abs(atomerr))),
  'minimum_accepted_species_mol_m2':float(n.min()),
  'total_entropy_change_J_m2_K':float(ent[-1]-ent[0]),
  'min_surface_entropy_production_W_m2_K':float(min(rn*af/T)),
  'surface_entropy_produced_J_m2_K_quadrature':float(trapezoid(rn*af/T,sol.t)),
  'max_forward_NO_collision_probability':float(max(2*rf/denom[4])),
  'max_reverse_N2_collision_probability':float(max(rr/denom[0])),
  'max_reverse_O2_collision_probability':float(max(rr/denom[1])),
  'log_K_decomposition_initial_final':[profiles[0][4],profiles[-1][4]],
  'output_file':f'completion_lambda_{lam:g}.npz'
 }, dict(t=sol.t,n=n,T=T,extent=sol.y[7],surface_forward=rf,surface_reverse=rr,affinity_J_mol=af,energy=en,entropy=ent)

