"""Finite diagnostic of the frozen-transcript identity; no finite-tree inference."""
import numpy as np
rng = np.random.default_rng(2102026)
# Sender starts with a K=2 logical system. She isometrically emits qutrit X1,
# keeping a 2-dimensional memory A. Bob measures Y1 in a random basis,
# sends t, and Alice applies a t-dependent isometry A -> X2 (qutrit).
# Device is the genuine tree edge reversal, starting at a nonroot vertex for this test.
K, d, a = 2, 3, 2
v_start = (1,)

def iso(rows, cols):
    q, r = np.linalg.qr(rng.normal(size=(rows,cols))+1j*rng.normal(size=(rows,cols)))
    return q[:, :cols]
A1 = iso(a*d,K).reshape(a,d,K)
A2 = [iso(d,a) for _ in range(d)]
Q = iso(d,d)  # measurement basis columns

def edge(x,v):
    if len(v)==0: return 0,(x,)
    if x==0: return v[-1],v[:-1]
    return 0,v+(x,)

# Endpoint set generated by two genuine interactions, no reflected boundary.
endpoints = sorted({edge(x2,edge(x1,v_start)[1])[1] for x1 in range(d) for x2 in range(d)})
C={w:np.zeros((d*d,d*d),complex) for w in endpoints}
for x1 in range(d):
  y1,v1=edge(x1,v_start)
  for x2 in range(d):
    y2,w=edge(x2,v1)
    C[w][y1*d+y2,x1*d+x2]=1

errors=[]
Fs=[]
for t in range(d):
    # Artificial frozen encoder E_t (all ports prepared before device).
    Et=np.einsum('bx,xyk->ybk',A2[t],A1).reshape(d*d,K)
    # Bob has measured Y1 and retains Y2 as his quantum output.
    Dt=np.zeros((d,d*d),complex)
    for y1 in range(d):
      for y2 in range(d): Dt[y2,y1*d+y2]=np.conj(Q[y1,t])
    for w in endpoints:
        fact=Dt@C[w]@Et
        # Actual chronological contraction, including measurement before A2[t].
        direct=np.zeros((d,K),complex)
        for k in range(K):
          for aa in range(a):
            for x1 in range(d):
              y1,v1=edge(x1,v_start)
              after_measure=A1[aa,x1,k]*np.conj(Q[y1,t])
              for x2 in range(d):
                y2,w2=edge(x2,v1)
                if w2==w: direct[y2,k]+=A2[t][x2,aa]*after_measure
        errors.append(np.linalg.norm(direct-fact))
        Fs.append(fact)
complete=sum(F.conj().T@F for F in Fs)
print('Seed:',2102026)
print('Slots: 2; independent sender memory: 2; qutrit feedback outcomes: 3')
print('Initial vertex:',v_start)
print('Genuine tree endpoints:',endpoints)
print('Maximum Frobenius norm of chronological-minus-factorized branch:',max(errors))
print('Completeness error ||sum F*F-I||_F:',np.linalg.norm(complete-np.eye(K)))
print('Block Kraus ranks:',[int(np.linalg.matrix_rank(C[w])) for w in endpoints])
probs = np.array([[sum(np.linalg.norm(Fs[t*len(endpoints)+j][:,k])**2 for j in range(len(endpoints))) for t in range(d)] for k in range(K)])
print('Transcript probabilities for two logical basis inputs:',probs.tolist())
print('Outcome-distribution change between logical inputs:',np.linalg.norm(probs[0]-probs[1]))
assert np.linalg.norm(probs[0]-probs[1])>1e-4
assert max(errors)<1e-12
assert np.linalg.norm(complete-np.eye(K))<1e-12
print('PASS: every tested unnormalized branch factors; all outcomes sum to TP.')
