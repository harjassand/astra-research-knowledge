"""Actual [[5,1,2]] seed RX3 local recognition with all redundant checks.
Tests local Cx/Cq image flags, diagonal endpoint flags and reconstruction.
This is a one-step fixture, not the memory decoder's level2 terminal lookup.
"""
import sys,json,random
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent/'helpers'))
from actual_generic_rx import rx
from gf2 import pivots,member
Xold=[0b10011,0b11100];Zold=[0b10101,0b11010]
X,Z,Q,F=rx(Xold,Zold,5,3);n=len(Q);r=len(Z)
cols=[sum(((z>>q)&1)<<j for j,z in enumerate(Z)) for q in range(n)]
def syndrome(e):
 s=0
 while e:
  t=e&-e;s^=cols[t.bit_length()-1];e^=t
 return s

def mask(vs):return sum(1<<v for v in vs)
CX={x:[q for q,v in enumerate(Q) if v[:2]==('xe',x)] for x in range(2)}
CQ={q:[i for i,v in enumerate(Q) if v[:2]==('qv',q)] for q in range(5)}
RX={x:[] for x in range(2)};RQ={q:[] for q in range(5)};RZ={}
for j,z in enumerate(Z):
 names=[Q[q] for q in range(n) if z>>q&1]
 if all(v[0]=='xe' for v in names):
  xs={v[1] for v in names};assert len(xs)==1;RX[next(iter(xs))].append(j)
 elif any(v[0]=='xe' for v in names):
  qs={v[1] for v in names if v[0]=='qv'};assert len(qs)==1;RQ[next(iter(qs))].append(j)
 else:
  endpoints={v[2] for v in names};assert len(endpoints)==1
  layer,vertex=next(iter(endpoints));assert vertex[0]=='z';RZ[vertex[1],layer]=j
mx={x:mask(v) for x,v in RX.items()};mq={q:mask(v) for q,v in RQ.items()};mz=mask(RZ.values())
allq=mask(j for vs in RQ.values() for j in vs)
def table(qs,inside,outside):
 T={};seen=set();e=s=prev=0
 for k in range(1<<len(qs)):
  gray=k^(k>>1)
  if k:
   b=(gray^prev).bit_length()-1;q=qs[b];e^=1<<q;s^=cols[q]
  prev=gray;key=s&inside;seen.add(key)
  if (s&outside).bit_count()<=key.bit_count() and (key not in T or e<T[key][0]):T[key]=(e,s)
 assert set(T)==seen and T[0]==(0,0)
 return T
TX={x:table(CX[x],mx[x],allq) for x in CX}
TQ={q:table(CQ[q],mq[q],mz) for q in CQ}
def recognize(s):
 f=change=0
 for x in CX:
  t=TX[x].get(s&mx[x])
  if t is None:return False,None
  f^=t[0];change^=t[1]
 s1=s^change;assert s1.bit_count()<=s.bit_count()
 change=0
 for q in CQ:
  t=TQ[q].get(s1&mq[q])
  if t is None:return False,None
  f^=t[0];change^=t[1]
 s2=s1^change;assert s2.bit_count()<=s1.bit_count()
 parent=0
 for z in range(2):
  a=(s2>>RZ[z,0])&1;b=(s2>>RZ[z,1])&1
  if a!=b:return False,None
  parent|=a<<z
 assert not s2&~mz
 lift=0
 # parent Z-syndrome bit0/1 is generated by old TL/TR respectively.
 for z in range(2):
  if parent>>z&1:lift^=F[z]
 assert syndrome(f^lift)==s
 assert 2*parent.bit_count()<=s.bit_count()
 return True,f^lift
P=pivots(cols);rng=random.Random(20261101)
counts=dict(valid_generated=0,random_accepted=0,random_rejected=0)
inputs=[syndrome(rng.getrandbits(n)) for _ in range(3000)]+[rng.getrandbits(r) for _ in range(3000)]+[0]+[1<<j for j in range(r)]
for i,s in enumerate(inputs):
 ok,f=recognize(s);assert ok==member(s,P)
 if i<3000:assert ok;counts['valid_generated']+=1
 elif i<6000:counts['random_accepted' if ok else 'random_rejected']+=1
 if ok:assert syndrome(f)==s
result=dict(n=n,Zchecks=r,syndrome_rank=len(P),tested_inputs=len(inputs),counts=counts,
 Cx_table_sizes={str(x):len(TX[x]) for x in TX},Cq_table_sizes={str(q):len(TQ[q]) for q in TQ},
 all_local_solvable_inputs_have_admissible_weight_bounded_correction=True,
 flags_equivalent_to_global_image_on_all_tested_inputs=True,all_accepted_reconstructions_exact=True)
print(json.dumps(result,indent=2));open(Path(__file__).with_name('actual_main_seed_recognizer_results.json'),'w').write(json.dumps(result,indent=2))
