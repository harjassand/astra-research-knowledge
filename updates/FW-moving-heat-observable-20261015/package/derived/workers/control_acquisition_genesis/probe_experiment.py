for design in ['two_anchor', 'random']:
    rows = [row for row in selected if row['design']==design]
    fitting[design] = dict(instances=len(rows),
        median_full_table_rmse=float(np.median([r['all_table']['rmse'] for r in rows])),
        worst_full_table_absolute_error=max(r['all_table']['max_abs'] for r in rows),
        median_heldout_rmse=float(np.median([r['heldout']['rmse'] for r in rows])),
        fitting_seconds_all_starts=sum(r['runtime_seconds'] for r in fit_rows if r['design']==design))
by_instance = {(r['m'], r['seed'], r['design']):r for r in selected}
fitting['random_wins_paired_full_table'] = sum(
    by_instance[(m, seed, 'random')]['all_table']['rmse'] <
    by_instance[(m, seed, 'two_anchor')]['all_table']['rmse']
    for m in range(5, 11) for seed in range(2))

