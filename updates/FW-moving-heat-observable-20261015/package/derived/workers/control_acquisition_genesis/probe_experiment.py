"""Independent port-probe intervention on the supplied accretive needle family.

All responses here are generated by explicitly labelled synthetic matrices.
The reconstruction routines receive only m and an oracle; no hidden bits are
passed to them. No hardware acquisition or global arbitrary-plant claim.
"""
