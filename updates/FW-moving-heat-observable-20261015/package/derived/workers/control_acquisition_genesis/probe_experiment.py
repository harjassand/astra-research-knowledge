START = time.perf_counter()


def matrix(bits, order=None, scaled=False):
    """Closed-form coefficients, independently of the source's update code."""
    m = len(bits)
    eps = 1 / m**2
    if order is None:
        order = list(range(m))
    sb = [bits[i] for i in order]
    a = np.zeros((m, m))
    beta = np.zeros(m)
    gamma = np.zeros(m)
    for i in range(m):
        a[i, i] = eps
        beta[i] = eps * math.prod(sb[:i])
        gamma[i] = (1 - 2 * sb[i]) * math.prod(sb[i + 1 :])
        for j in range(i):
            a[i, j] = -eps * (1 - 2 * sb[j]) * math.prod(sb[j + 1 : i])
    base = np.zeros((m + 2, m + 2))
    base[0, 0] = base[-1, -1] = eps
    for i, port in enumerate(order):
        base[port + 1, 0] = -beta[i]
        base[-1, port + 1] = -eps * gamma[i]
        for j, other in enumerate(order):
            base[port + 1, other + 1] = a[i, j]
    base[-1, 0] = -eps * math.prod(sb)
    if not scaled:
        return base, 1.0, eps, 1.0
    lam = 4 * m**2 * (m + 1) ** 2
    amp = 2 * (m + 1)
    return lam * base, lam, float(amp), float(amp)


def matrix_oracle(bits, order=None, scaled=False, delta=None, leakage=0.0):
    m = len(bits)
    base, ctl, source_amp, detector_amp = matrix(bits, order, scaled)
    if delta is not None:
        base = base + delta

    def read(port, u):
        applied = np.clip(np.asarray(u, dtype=float) + leakage, 0, 1)
        mat = base + np.diag(np.r_[0, ctl * applied, 0])
        source = np.zeros(m + 2)
        source[port + 1] = source_amp
        return float(detector_amp * np.linalg.solve(mat, source)[-1])

    return read


def product_response(bits, u):
    eps = 1 / len(bits) ** 2
    return math.prod(v / (eps + v) if bit else eps / (eps + v)
                     for bit, v in zip(bits, u))


def probe_formula(bits, port, u, order=None):
    m = len(bits)
    eps = 1 / m**2
    if order is None:
        order = list(range(m))
    k = order.index(port)
    return ((1 - 2 * bits[port]) * eps / (eps + u[port]) *
            math.prod(u[j] / (eps + u[j]) if bits[j] else eps / (eps + u[j])
                      for j in order[k + 1 :]))


def ordered_recover(m, oracle):
    """Known ordered stage labels; scalar signed observations only."""
    u = np.zeros(m)
    result = [None] * m
    transcript = []
    for port in reversed(range(m)):
        y = oracle(port, u.copy())
        result[port] = int(y < 0)
        transcript.append(dict(port=port, u=u.tolist(), response=y))
        u[port] = result[port]
    return result, transcript


def unordered_recover(m, oracle, threshold=0.25):
    """Unknown ordering, but the common chain-family promise is known.

    Each round probes every unresolved port without changing controls mid-round.
    A nonzero signed suffix response classifies that port; newly found bit-1
    ports are activated only after the round. An empty round means abstention.
    """
    u = np.zeros(m)
    result = [None] * m
    transcript = []
    for round_index in range(m):
        found = []
        for port in range(m):
            if result[port] is not None:
                continue
            y = oracle(port, u.copy())
            transcript.append(dict(round=round_index, port=port,
                                   u=u.tolist(), response=y))
            if y > threshold:
                found.append((port, 0))
            elif y < -threshold:
                found.append((port, 1))
        if not found:
            return None, transcript
        for port, bit in found:
            result[port] = bit
            u[port] = bit
        if all(bit is not None for bit in result):
            return result, transcript
    return None, transcript


def exact_probe(bits, port, u):
    """Exact rational forward substitution through the physical matrix."""
    m = len(bits)
    eps = F(1, m*m)
    x = []
    # Extra local source has y0=0; each preceding row is driven by epsilon*y.
    # Only selected internal row receives independent epsilon injection.
    y = F(0)
    for i, bit in enumerate(bits):
        xi = eps * (y + int(i == port)) / (eps + u[i])
        x.append(xi)
        y = xi if bit == 0 else y - xi
    return y


checks = []
exact_max_float_error = 0.0
matrix_max_error = 0.0
native_transfer_max_error = 0.0
minimum_deployed_native_response = 1.0
minimum_probe_contrast = 1.0
minimum_accretivity_ratio = float('inf')
exact_rational_identities = 0
ordered_cases = 0
unordered_cases = 0
bounded_noise_cases = 0
worst_unordered_ratio = 0.0

# Exact formulas and independent dense matrix solves for every small label.
for m in range(1, 9):
    for bits_tuple in product((0, 1), repeat=m):
        bits = list(bits_tuple)
        uf = [F(i + 1, m + 2) for i in range(m)]
        ud = np.array([float(x) for x in uf])
        dense = matrix_oracle(bits)
        native_transfer_max_error = max(native_transfer_max_error,
            abs(dense(-1, ud)-product_response(bits, ud)))
        for port in range(m):
            exact = exact_probe(bits, port, uf)
            eps = F(1, m*m)
            expected = ((1 - 2*bits[port]) * eps / (eps + uf[port]) *
                        math.prod(uf[j]/(eps + uf[j]) if bits[j] else eps/(eps + uf[j])
                                  for j in range(port+1, m)))
            assert exact == expected
            exact_rational_identities += 1
            err = abs(dense(port, ud) - float(exact))
            matrix_max_error = max(matrix_max_error, err)
        base, _, _, _ = matrix(bits)
        delta = (1/m**2)/(4*(m+1)**2)
        minimum_accretivity_ratio = min(
            minimum_accretivity_ratio,
            float(np.linalg.eigvalsh((base + base.T)/2).min())/delta)
        recovered, transcript = ordered_recover(m, dense)
        assert recovered == bits
        deployed = dense(-1, np.array(recovered))
        minimum_deployed_native_response = min(minimum_deployed_native_response, deployed)
        assert deployed >= 0.5-1e-14
        ordered_cases += 1
        minimum_probe_contrast = min(minimum_probe_contrast,
                                     min(abs(x['response']) for x in transcript))
        recovered, transcript = unordered_recover(m, dense)
        assert recovered == bits
        assert len(transcript) <= m*(m+1)//2
        unordered_cases += 1
        worst_unordered_ratio = max(worst_unordered_ratio,
                                    len(transcript)/(m*(m+1)/2))
        # Deliberately adversarial bounded error toward zero on strong signals,
        # away from zero on the exact-zero branch. It cannot cross 1/4.
        def bounded(port, u):
            y = dense(port, u)
            e = -math.copysign(3/16, y) if abs(y)>0.25 else 3/16
            return y+e
        recovered, transcript = unordered_recover(m, bounded)
        assert recovered == bits
        bounded_noise_cases += 1
    checks.append(dict(m=m, labels=2**m, complete=True))

# Unknown permutations, larger matrices, symmetric constant-margin scaling,
# calibrated off-state leakage, and full-matrix perturbations.
rng = np.random.default_rng(20261015)
stress = []
for m in [4, 8, 16, 32, 64]:
    for trial in range(8):
        bits = rng.integers(0, 2, m).tolist()
        order = rng.permutation(m).tolist()
        # The fully-one case attains the worst-case m(m+1)/2 probe count.
        if trial == 0:
            bits = [1]*m
        n = m+2
        raw_delta = rng.normal(size=(n, n))
        bnorm = 4*(m+1)**2
        delta_bound = 1/(128*bnorm)
        perturb = raw_delta*(delta_bound/np.linalg.norm(raw_delta, 2))
        leakage = 1/(128*m**3)
        oracle = matrix_oracle(bits, order, scaled=True, delta=perturb,
                               leakage=leakage)
        recovered, transcript = unordered_recover(m, oracle)
        assert recovered == bits
        worst_formula_error = max(abs(item['response']-probe_formula(
            bits, item['port'], np.array(item['u']), order)) for item in transcript)
        # Loose uniform estimates: perturb <=1/64, control leakage <=1/128.
        assert worst_formula_error < 3/128
        stress.append(dict(m=m, trial=trial, readings=len(transcript),
                           recovered=True, perturbation_norm=delta_bound,
                           absolute_control_leakage=leakage,
                           max_output_difference_from_ideal=worst_formula_error))

# Fixed-source blind-query information budget versus the new interface.
complexity = []
for m in [8, 16, 32, 64]:
    count = m*(m+1)//2
    failure_probability = 0.01
    sigma = 0.5
    repeats = max(1, math.ceil(512*sigma*sigma*math.log(2*count/failure_probability)))
    target_probability = 1-failure_probability
    fixed_source_min_inverse_variance = 4*(2**m)*(max(target_probability-4/(2**m), 0))**2
    complexity.append(dict(m=m, new_settings_ordered=m,
                           new_settings_unknown_order=count,
                           gaussian_sd_per_raw_read=sigma,
                           gaussian_repeats_sufficient_for_error_1_over_16=repeats,
                           raw_read_budget_unknown_order=count*repeats,
                           new_inverse_variance_upper_budget=count*repeats/sigma**2,
                           common_target_success_probability=target_probability,
                           fixed_source_inverse_variance_lower_bound=fixed_source_min_inverse_variance,
                           fixed_source_raw_reading_lower_bound_same_sigma=sigma**2*fixed_source_min_inverse_variance))

# Recompute the strongest supplied fitting comparison from its immutable rows.
