"""Independent exact audit of the proposed two-scale law and acoustic flatness."""
import sympy as s

a,b,c,d,z=s.symbols('a b c d z', real=True)
X=s.Matrix([a,b,c,d])
u=a*a+c*c
v=b*b+d*d
w=a*b+c*d
q=a*d-b*c
G=s.expand(3*(u+v-2*q)**2+s.Rational(35,24)*u**2+q**2-s.Rational(5,2)*q*u)
vars=s.Matrix([a,b,c,d])
DG=s.Matrix([s.diff(G,x) for x in vars])
HG=s.hessian(G,vars)

def subst_matrix(A, vals):
    return A.subs({a:vals[0],b:vals[1],c:vals[2],d:vals[3]}).applyfunc(s.factor)

e=s.symbols('e', positive=True, real=True)
R=[0,1,0,0]
S=[0,0,1,0]
B=[0,1,6*e**2,0]
T=[2,0,0,3]
# A symmetric polynomial in z=e^2; prove exact factorization for H.
H=subst_matrix(HG,B)*(1-e**2/(2+e**2))+subst_matrix(HG,T)*(2*e**2/(2+e**2))
Hz=s.simplify((2+e**2)*H/2)
# This is H=2/(2+z) [ HG(B)+z HG(T) ]; simplify with z=e^2.
assert Hz.applyfunc(s.factor)==(subst_matrix(HG,B)+e**2*subst_matrix(HG,T)).applyfunc(s.factor)
mins=[]
for k in range(1,5):
    mins.append(s.factor(Hz[:k,:k].det()))
print('H scalar factor: 2/(2+e^2) times matrix with leading minors:')
for m in mins: print(m)
print('det H factor:',s.factor(H.det()))

# Check sign of all principal minors at e^2>0 through exact coefficient positivity after z substitution.
# The entries are even powers of e; replace e^2=z and factor univariate polynomials.
for i,m in enumerate(mins):
    poly=s.Poly(m,e)
    assert all(coef >= 0 for _,coef in poly.terms()), (i+1,m)
    assert m.subs(e,1)>0

# Moments and coupling for the four-atom law.
# Weights: (1-p)/2 at +/-B; 2p/3 at T; p/3 at -2T.
p=e**2/(2+e**2)
weights=[(1-p)/2,(1-p)/2,2*p/3,p/3]
pts=[B,[0,-1,-6*e**2,0],T,[-4,0,0,-6]]
mean=s.zeros(4,1)
mean_det=0
C=s.zeros(4,4)
m4=0
for wt,pt in zip(weights,pts):
    x=s.Matrix(pt); mean += wt*x
    det=x[0]*x[3]-x[1]*x[2]
    mean_det += wt*det
    C += wt*x*x.T
    m4 += wt*(x.dot(x))**2
assert mean.applyfunc(s.factor)==s.zeros(4,1)
assert s.factor(mean_det)==0
print('mean:',mean.applyfunc(s.factor).T)
print('mean det:',s.factor(mean_det))
print('covariance:',C.applyfunc(s.factor))
print('covariance determinant:',s.factor(C.det()))
print('E|X|^4:',s.factor(m4))
print('p:',p)

# Directional Schur loss on the background line R*I.
I=s.Matrix([1,0,0,1])
bvec=s.zeros(4,1)
Hlaw=s.zeros(4,4)
claw=0
for wt,pt in zip(weights,pts):
    x=s.Matrix(pt)
    sub={a:x[0],b:x[1],c:x[2],d:x[3]}
    bvec += wt*DG.subs(sub)
    Hlaw += wt*HG.subs(sub)
    claw += wt*G.subs(sub)
bI=s.factor((bvec.T*I)[0])
HI=s.factor((I.T*Hlaw*I)[0])
line_loss=s.factor(bI**2/(2*HI))
assert s.factor(bI-s.Rational(20,3)*p)==0
assert s.factor(HI-30*(1-p)*e**4)==0
assert s.factor(line_loss-s.Rational(5,27)*(1-p))==0
print('b:I, I:H I, directional Schur loss:',bI,HI,line_loss)
print('c:',s.factor(claw))
full_loss=s.factor((bvec.T*Hlaw.inv()*bvec)[0]/2)
full_gap=s.factor(claw-full_loss)
print('full optimized loss and gap:',full_loss,full_gap)
print('full loss limit:',s.limit(full_loss,e,0),'full gap limit:',s.limit(full_gap,e,0))

# Covariance in row-major R^4: rank exactly two, generated by B and T.
C_expected=(1-p)*s.Matrix(B)*s.Matrix(B).T+2*p*s.Matrix(T)*s.Matrix(T).T
assert C.applyfunc(s.factor)==C_expected.applyfunc(s.factor)
assert C.rank()==2
# Each support atom is uniformly bounded for 0<e<1/10; the rare mass is p->0.
assert s.limit(m4,e,0)==1
print('row-major covariance rank:',C.rank(),'; fourth moment limit:',s.limit(m4,e,0))

# Coupling: U~Unif[0,1], intervals in order +B,-B,T,-2T with the law weights.
# As e->0 their boundaries approach 1/2 and 1, so X_e->sgn(1/2-U)R a.e.;
# the rare region has measure p=O(e^2), and all supports are uniformly bounded.
# Hence E|X_e-X_0|^4 ->0, proving strong L^4 under this explicit coupling.

# Determinants of all pairwise support differences.  They are nonzero in 0<e<0.1.
atom_pairs=[]
for i in range(4):
    for j in range(i+1,4):
        xi=s.Matrix(pts[i]); xj=s.Matrix(pts[j])
        mat=s.Matrix([[xi[0]-xj[0],xi[1]-xj[1]],[xi[2]-xj[2],xi[3]-xj[3]]])
        det=s.factor(mat.det())
        atom_pairs.append(det)
        assert s.factor(det)!=0
print('pairwise support-difference determinants:',atom_pairs)

# The plane span(B,T) has det(s B+t T)=6(t^2-e^2 s^2): its only
# rank-one lines are B+eT and B-eT.
ss,uu=s.symbols('ss uu',real=True)
plane_det=s.factor((ss*s.Matrix([[B[0],B[1]],[B[2],B[3]]])+uu*s.Matrix([[2,0],[0,3]])).det())
assert s.factor(plane_det-6*(uu**2-e**2*ss**2))==0

# Normalized distinct rank-one directions and acoustic Rayleigh upper bound.
D=s.factor(s.Matrix(B).dot(s.Matrix(B))+e**2*s.Matrix(T).dot(s.Matrix(T)))
Rp=s.Matrix([B[i]+e*T[i] for i in range(4)])
Rm=s.Matrix([B[i]-e*T[i] for i in range(4)])
assert s.factor(Rp[0]*Rp[3]-Rp[1]*Rp[2])==0
assert s.factor(Rm[0]*Rm[3]-Rm[1]*Rm[2])==0
assert s.factor(Rp.dot(Rp)-D)==0 and s.factor(Rm.dot(Rm)-D)==0
s2=s.factor(1-(Rp.dot(Rm)/D)**2)
assert s.factor(s2-52*e**2*(1+36*e**4)/D**2)==0
# At I, D^2G(B +/- eT)[I,I]=30e^4. For unit atoms, divide by D.
assert s.factor((I.T*subst_matrix(HG,Rp)*I)[0]-30*e**4)==0
assert s.factor((I.T*subst_matrix(HG,Rm)*I)[0]-30*e**4)==0
rayleigh=s.factor(30*e**4/D)
# For the acoustic sum, Rayleigh quotient at I divides the two-term sum by |I|^2=2.
assert s.factor(((I.T*(subst_matrix(HG,Rp)+subst_matrix(HG,Rm))*I)[0]/D)/I.dot(I)-rayleigh)==0
print('D, squared angle separation, acoustic upper bound:',D,s2,rayleigh)
print('asymptotic ratio upper bound / s^2:',s.limit(rayleigh/s2,e,0))
