#!/usr/bin/env python3
"""Independent covariance recurrence and rational receipt/mask aggregation."""
from fractions import Fraction as F
from pathlib import Path
import json,math,time
import numpy as np
from rarepath_certificate import (identity,add,diag,multiply,transpose,
    make_coupled_model,normal_sf_interval,exp_negative_interval,floor_grid)

HERE=Path(__file__).resolve().parent


def rational(record):
    return F(int(record['numerator']),int(record['denominator']))


def run():
    started=time.perf_counter()
    model=make_coupled_model()
    certificate=json.loads((HERE/'exact_certificate.json').read_text())
    receipt=json.loads((HERE/'receipt.json').read_text())
    # This covariance recursion differs from the innovation coefficient method.
    dt=F(1,8)
    b=[[-F(1),F(0),F(1)],[F(0),-F(1),-F(1)],
       [F(1,100),-F(1,100),-F(3,100)]]
    a=add(identity(3),[[dt*x for x in row] for row in b])
    cov=diag([0,0,1]);noise=diag([F(1,4),F(1,4),F(1,400)])
    for k in range(16):
        cov=add(multiply(multiply(a,cov),transpose(a)),noise)
        assert cov[0][0]==model['variance'][2*k]
        assert cov[1][1]==model['variance'][2*k+1]
    lows=[];ups=[]
    for v,row in zip(model['variance'],certificate['tail_bounds']):
        lo,hi=normal_sf_interval(F(17,2)**2/v)
        assert rational(row['variance'])==v
        assert rational(row['lower'])==lo and rational(row['upper'])==hi
        lows.append(lo);ups.append(hi)
    total=sum(ups,F(0))
    assert rational(certificate['union_mass_upper'])==total
    records=np.load(HERE/'sample_masks.npz')['event_masks']
    sample_lo=F(0);sample_hi=F(0)
    for mask_int in records:
        mask=int(mask_int)
        active=[j for j in range(32) if (mask>>j)&1]
        assert active
        sample_lo+=floor_grid(total/sum((ups[j]/lows[j] for j in active),F(0)),70)
        sample_hi+=total/len(active)
    sample_lo/=len(records);sample_hi/=len(records)
    assert sample_lo==rational(certificate['sample_mean_lower'])
    assert sample_hi==rational(certificate['sample_mean_upper'])
    epsilon=F(1,100)
    _,tail=exp_negative_interval(2*len(records)*epsilon**2)
    assert 2*tail<F(1,20)
    lower=max(rational(certificate['deterministic_lower']),sample_lo-epsilon*total)
    upper=min(total,sample_hi+epsilon*total)
    assert lower==rational(certificate['confidence_lower'])
    assert upper==rational(certificate['confidence_upper'])
    histogram=np.bincount(np.asarray([int(int(m).bit_count()) for m in records]),minlength=33)
    assert histogram.tolist()==receipt['bounded_sampler']['contribution_multiplicity_histogram']
    # Check source content pins, without writing to their locations.
    import hashlib
    for row in json.loads((HERE/'source_pins.json').read_text()):
        assert hashlib.sha256(Path(row['path']).read_bytes()).hexdigest()==row['sha256']
    out={'status':'PASS','checks':[
        '32 exact innovation variances match independent 3x3 covariance recursion',
        'all rational Gaussian-tail endpoints regenerate exactly',
        '20000 stored event masks aggregate to recorded interval endpoints exactly',
        'fixed-n Hoeffding failure bound < .05 by rational exp enclosure',
        'source byte hashes remain pinned'],
        'scope_exclusion':'event masks generated by float Gaussian sampler are not themselves interval-certified exact samples',
        'execution_seconds':time.perf_counter()-started}
    (HERE/'verification_receipt.json').write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps(out,indent=2))


if __name__=='__main__':
    run()
